"""Stage 6: reports for people (Markdown) and tools (SARIF 2.1.0)."""
from __future__ import annotations

from . import __version__

SEV_ORDER = ["critical", "high", "medium", "low", "info"]
SARIF_LEVEL = {"critical": "error", "high": "error", "medium": "warning", "low": "note", "info": "note"}


def _esc(s: str) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def to_markdown(res) -> str:
    c = res.counts
    n = res.narrative
    by_id = {f.id: f for f in res.findings}
    lines = [
        "# Assay security assessment report",
        "",
        f"- **Scope:** local directory `{res.scope_root.rsplit('/', 1)[-1]}` ({c['files']} files). Static review "
        "only: no hosts were scanned, no code was executed, nothing was changed.",
        f"- **Result:** {c['findings']} findings, {c['chains']} attack chains. By severity: "
        + ", ".join(f"{s} {c['by_severity'].get(s, 0)}" for s in SEV_ORDER) + ".",
        f"- **Generated by:** Assay {__version__}. Briefing written by: {n['author']}.",
        "",
        "## Briefing",
        "",
        n["text"]["summary"],
        "",
        "**First steps:**",
        "",
    ]
    for s in n["text"]["first_steps"]:
        f = by_id.get(s["finding_id"])
        where = f" ({f.file}:{f.line})" if f else ""
        lines.append(f"1. `{s['finding_id']}`{where}: {s['why']}")
    lines += ["", "## Attack chains (correlated findings)", ""]
    if not res.chains:
        lines.append("No multi-step chains were found.")
    for ch in res.chains:
        lines += [f"### {ch.id} [{ch.severity}] {ch.title}", "", ch.narrative, "",
                  "Built from: " + ", ".join(f"`{i}`" for i in ch.finding_ids), ""]
    lines += ["## Findings by priority", "", "| Score | Severity | ID | Finding | Location |", "|---|---|---|---|---|"]
    for f in res.findings:
        lines.append(f"| {f.score} | {f.severity} | `{f.id}` | {_esc(f.title)} | `{f.file}:{f.line}` ({_esc(f.resource)}) |")
    lines += ["", "## Finding details", ""]
    for f in res.findings:
        if f.severity == "info":
            continue
        lines += [f"### `{f.id}` {f.title}", "",
                  f"- **Rule:** {f.rule_id} {('(' + f.cwe + ')') if f.cwe else ''}; severity {f.severity}, "
                  f"confidence {f.confidence}; score {f.score} = " + "; ".join(f.score_factors),
                  f"- **Where:** `{f.file}:{f.line}`, {f.resource}",
                  f"- **Evidence:** `{_esc(f.evidence)}`",
                  f"- **Why it matters:** {f.rationale}",
                  f"- **Fix:** {f.remediation}", ""]
    lines += ["## Proposed actions (awaiting human approval)", ""]
    if not res.actions:
        lines.append("No mechanical patches proposed; all fixes above are manual.")
    else:
        lines.append("Nothing has been applied. Approve specific IDs with `assay approve <run-dir> A-01 ...`, then "
                     "`assay apply <run-dir>`.")
        lines.append("")
        for a in res.actions:
            lines += [f"### {a.id}: {a.description}", "", "```diff", a.diff.rstrip(), "```", ""]
    lines += ["## Agent decisions", "", "| Stage | Decision | Reason |", "|---|---|---|"]
    for d in res.decisions:
        lines.append(f"| {d.stage} | {_esc(d.action)} | {_esc(d.reason)} |")
    lines += ["", "_Secrets are shown redacted (first 4 characters and length only). Findings come from "
              "deterministic rules; a human should confirm them before acting._", ""]
    return "\n".join(lines)


def to_sarif(res) -> dict:
    rules = {}
    results = []
    for f in res.findings:
        rules.setdefault(f.rule_id, {
            "id": f.rule_id, "shortDescription": {"text": f.title},
            "help": {"text": f.remediation},
            "properties": {"tags": [t for t in [f.cwe, f.category] if t]},
        })
        results.append({
            "ruleId": f.rule_id, "level": SARIF_LEVEL[f.severity],
            "message": {"text": f"{f.title}. {f.rationale} Evidence: {f.evidence}"},
            "locations": [{"physicalLocation": {"artifactLocation": {"uri": f.file},
                                                "region": {"startLine": max(f.line, 1)}}}],
            "partialFingerprints": {"assayId": f.id},
            "properties": {"severity": f.severity, "score": f.score, "confidence": f.confidence},
        })
    return {"$schema": "https://json.schemastore.org/sarif-2.1.0.json", "version": "2.1.0",
            "runs": [{"tool": {"driver": {"name": "Assay", "version": __version__, "rules": list(rules.values())}},
                      "results": results}]}
